// Run the complete desktop flow, then exercise subscription changes through the projection.
import './smoke-ui.mjs';
import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';

const browser=await chromium.connectOverCDP('http://127.0.0.1:19156');
const page=browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('index.html'));
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const state=await page.evaluate(()=>window.bench.inspect());
const book=state.windows.find(w=>w.appId==='spreadsheet');
const chart=state.charts[0];
const projection=state.projections.find(w=>w.sourceAppId==='charts');
const view=page.locator(`[data-testid="app-window"][data-window-id="${projection.windowId}"]`);
await view.locator('[data-testid="chart-disconnect"]').click();
await page.waitForFunction(id=>window.nest.getWindow(id).data.connectionState==='disconnected',chart.windowId);
await page.locator(`[data-testid="taskbar-item"][data-window-id="${book.id}"]`).click();
const sheet=page.locator(`[data-testid="app-window"][data-window-id="${book.id}"]`);
await sheet.locator('[data-cell-address="B2"]').dblclick();
await sheet.locator('[data-cell-address="B2"] input').fill('40');
await sheet.locator('[data-cell-address="B2"] input').press('Enter');
assert.equal(await sheet.locator('[data-cell-address="D2"]').textContent(),'240');
await sheet.locator('[data-testid="window-minimize"]').click();
assert.equal(await page.evaluate(id=>window.nest.getWindow(id).data.table[1][3],chart.windowId),180);
await view.locator('[data-testid="chart-connect"]').click();
await page.waitForFunction(id=>window.nest.getWindow(id).data.table[1][3]===240,chart.windowId);
assert.equal(await page.evaluate(id=>window.nest.getWindow(id).data.view.table[1][3],projection.windowId),240);
await page.screenshot({path:path.join(os.tmpdir(),'nest-reconnected-chart.png')});
assert.deepEqual(errors,[]);
console.log('Projected disconnect, frozen cache, spreadsheet editing and reconnection PASS');
await page.evaluate(()=>window.bench.reset());
await browser.close();
