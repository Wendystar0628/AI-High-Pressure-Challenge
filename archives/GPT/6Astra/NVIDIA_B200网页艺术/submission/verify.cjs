// Run with: node verify.cjs. Tests numerical behavior, not visual implementation.
const assert = require('node:assert/strict');
global.window = global;
global.localStorage = { getItem: () => null, setItem: () => {} };
require('./compute.js');
const M = AtlasMath;
assert.equal(M.scalar(1.0625, 'FP8'), 1, 'E4M3 ties to even');
assert.equal(M.scalar(1.1875, 'FP8'), 1.25, 'E4M3 odd midpoint rounds upward');
assert.equal(M.scalar(1000, 'FP8'), 448, 'E4M3 finite saturation');
assert.equal(M.scalar(2 ** -25, 'FP16'), 0, 'FP16 subnormal tie');
assert.equal(M.scalar(3 * 2 ** -25, 'FP16'), 2 ** -23, 'FP16 subnormal even tie');
assert.deepEqual(M.quantize([.75, 1.25, 2.5, 6], 'FP4'), { scale: 1, values: [1, 1, 2, 6] });
assert.deepEqual(M.compute().c, [3.75, -1.875, 1.875, 13.125]);
assert.equal(M.compute().total, 16.875);
assert.equal(M.compute().operations, 16);
assert.equal(M.compute().gpus, 2);
M.state.load = 320;
assert.equal(M.compute().gb, 180);
assert.equal(M.compute().gpus, 1, 'exact capacity fits in one GPU');
M.state.precision = 'FP16';
assert.equal(M.compute().gb, 640);
assert.equal(M.compute().gpus, 4);
Object.assign(M.state, { a: [1, 2, 3, 4], b: [5, 6, 7, 8], sparse: false });
assert.deepEqual(M.compute().c, [19, 22, 43, 50]);
assert.equal(M.compute().total, 134);
M.state.sparse = true;
assert.deepEqual(M.compute().rawA, [1, 0, 0, 4]);
assert.deepEqual(M.compute().c, [5, 6, 28, 32]);
assert.equal(M.compute().operations, 8);
assert.equal(M.compute().total, 71);
const schedule = M.reduction(.6, 0);
assert.deepEqual(schedule.switchSums, [33, 38], 'both switches receive the actual sparse contributions');
assert.equal(M.reduction(.9, 0).arrived.some(Boolean), false, 'no GPU reports a result before its broadcast arrives');
assert.equal(M.reduction(.94, 3).arrived[3], true, 'initiating GPU receives its broadcast first');
assert.equal(M.reduction(.94, 3).arrived[2], false, 'last GPU still waits for its routed packet');
assert.equal(M.reduction(1, 3).arrived.filter(Boolean).length, 8, 'all eight devices eventually receive the result');
assert.equal(M.reduction(1, 3).total, 71);
Object.assign(M.state, { a: [0, 0, 0, 0], sparse: false });
assert.equal(M.compute().operations, 16, 'dense multiplication retains zero operations');
M.state.sparse = true;
assert.equal(M.compute().operations, 0, 'sparse multiplication skips zero contributions');
Object.assign(M.state, { a: [1, 2, 3, 4], sparse: false, precision: 'FP4' });
const payload = M.compute().payload;
assert.equal(payload.values.length, 16);
assert.equal(payload.scale, 1.375, 'generated memory block actually shares its E4M3 scale');
assert.deepEqual(payload.values.slice(0, 8), payload.values.slice(8), 'large load repeats the same A/B input');
M.reset();
console.log('Passed: quantization, rounding, shared scales, matrix multiplication, sparsity, reduction, capacity boundaries.');
