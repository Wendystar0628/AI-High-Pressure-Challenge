export function iconSvg(name) {
  return ICON_SVGS[name] || ICON_SVGS.doc;
}

export function iconForPath(filePath, itemType = 'file') {
  if (itemType === 'dir') return 'files';
  const p = String(filePath || '').toLowerCase();
  if (p.endsWith('.sheet')) return 'spreadsheet';
  if (p.endsWith('.scene') || p.endsWith('.rec')) return 'scene';
  if (p.endsWith('.nos') || p.endsWith('.nbc')) return 'code';
  if (p.endsWith('.snap')) return 'subsystem';
  return 'doc';
}
