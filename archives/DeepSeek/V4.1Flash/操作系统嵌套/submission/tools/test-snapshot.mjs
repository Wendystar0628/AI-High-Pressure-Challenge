import { NestedOS } from '../src/core/os.js';
const os = new NestedOS();
await os.init({}, null);
await os.start();
const a = os.createChildSystem('outer');
const b = os.createChildSystem(a.id);
await new Promise(r=>setTimeout(r,700));
os.pauseSystem(b.id);
const snap = os.createSnapshot(a.id);
console.log('snap', snap.ok, snap.size, os.getSnapshotMeta('outer').length);
const before = [...os.systems.keys()];
const fork = await os.restoreSnapshot('outer', snap.path, {fork:true});
console.log('fork', fork.ok, fork.rootId, 'systems', [...os.systems.keys()], 'orig', before);
const newRoot = os.sysById(fork.rootId);
console.log('newRoot', newRoot.name, newRoot.parentId, 'children', newRoot.children, 'windows', newRoot.windows.length, 'procs', newRoot.processes.length, 'kernel', newRoot.kernelPath);
console.log('orig still', os.sysById(a.id)?.state, os.sysById(b.id)?.state, 'carrier', !!os.carrierOf(newRoot));
const restore = await os.restoreSnapshot('outer', snap.path, {fork:false});
console.log('restore', restore.ok, 'systems', [...os.systems.keys()], 'aState', os.sysById(a.id)?.state, 'bState', os.sysById(b.id)?.state);
os.stopTicking(); process.exit(0);
