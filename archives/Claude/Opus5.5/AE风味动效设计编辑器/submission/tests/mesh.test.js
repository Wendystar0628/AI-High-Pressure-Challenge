global.window = globalThis;
for (const f of ['core/util','geom/path','geom/poly','geom/mesh']) require('../js/' + f + '.js');
const {Path: P, Poly, Mesh} = AE;
const ring = Poly.boolean([P.flatten(P.ellipse(0,0,200,200),0.5)],[P.flatten(P.ellipse(0,0,100,100),0.5)],'subtract');
const m = Mesh.extrude(ring, 60, 8, 3);
console.log('verts', m.pos.length/3, 'tris', m.idx.length/3, m.groups.map(g=>g.mat+':'+g.count), m.bb.map(x=>x.toFixed(1)));
const b = Mesh.box(100,100,100,10); console.log('box', b.idx.length/3, b.bb);
const t = Mesh.torus(100,30,32); console.log('torus', t.idx.length/3);
Mesh.deform(m, Mesh.twistFn(90,'y',200)); console.log('twist ok', m.bb.map(x=>x.toFixed(1)));
const mg = Mesh.merge([{mesh:b, m:null},{mesh:t, m:AE.U.M4.trans(10,0,0)}]); console.log('merge', mg.groups);
